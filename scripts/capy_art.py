"""Bayer-dither the Capy source sprites into the inline art the Deck ships.

Reads the grayscale PNGs in design/capy-art/ (drawn from our own mark by
make_sources.py), applies a 4x4 ordered Bayer threshold and writes
commonplace/web/static/deck-art-data.js: one small inline SVG per sprite, drawn
with currentColor so it follows the light, dark and Deck looks. Pure standard
library; the output is deterministic, and tests compare it byte for byte.

Usage: python3 scripts/capy_art.py [--check]
"""

import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "design" / "capy-art"
OUTPUT = ROOT / "commonplace" / "web" / "static" / "deck-art-data.js"
NAMES = (
    "clear",
    "bots",
    "column",
    "search",
    "loading",
    "header",
    "rule",
    "rail",
    "pipeline",
    "step-choose",
    "step-preview",
    "step-progress",
    "step-report",
)
BAYER4 = (0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5)


def read_gray_png(path):
    """Decode an 8-bit grayscale, non-interlaced PNG into rows of 0..255."""
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", f"{path.name}: not a PNG"
    pos, idat, header = 8, b"", None
    while pos < len(data):
        size, kind = struct.unpack(">I4s", data[pos : pos + 8])
        body = data[pos + 8 : pos + 8 + size]
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
        pos += 12 + size
    w, h, depth, color, _, _, interlace = header
    assert (depth, color, interlace) == (8, 0, 0), f"{path.name}: need 8-bit grayscale"
    raw = zlib.decompress(idat)
    rows, prev = [], bytes(w)
    for y in range(h):
        line = raw[y * (w + 1) : (y + 1) * (w + 1)]
        assert line[0] == 0, f"{path.name}: unfiltered rows only"
        prev = line[1:]
        rows.append(list(prev))
    return w, h, rows


def dither_svg(name):
    w, h, rows = read_gray_png(SOURCES / f"{name}.png")
    path = []
    for y, row in enumerate(rows):
        on = [v / 255 > (BAYER4[(y % 4) * 4 + x % 4] + 0.5) / 16 for x, v in enumerate(row)]
        cursor, x = None, 0
        while x < w:
            if not on[x]:
                x += 1
                continue
            end = x
            while end < w and on[end]:
                end += 1
            if cursor is None:
                path.append(f"M{x} {y + 0.5:g}h{end - x}")
            else:
                path.append(f"m{x - cursor} 0h{end - x}")
            cursor, x = end, end
    return (
        f'<svg viewBox="0 0 {w} {h}" width="{w * 2}" height="{h * 2}" fill="none" stroke="currentColor" '
        f'shape-rendering="crispEdges" focusable="false"><path d="{"".join(path)}"/></svg>'
    )


def render():
    lines = [
        "// Generated by scripts/capy_art.py from the sprites in design/capy-art/. Do not edit by hand.",
        "export const ART = {",
    ]
    lines += [f"  '{name}': '{dither_svg(name)}'," for name in NAMES]
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUTPUT.read_text(encoding="utf-8") == text else 1)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
