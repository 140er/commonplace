import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const url = (source) => `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
const read = (name) => readFile(new URL(`../commonplace/web/static/${name}`, import.meta.url), "utf8");
const apiUrl = url(await read("api.js"));
const { planView } = await import(url((await read("plan.js")).replace('"./api.js"', `"${apiUrl}"`)));
const free = { enabled: true, plan: "free", storage: { used: 12.5 * 1024 * 1024, limit: 250 * 1024 * 1024 }, transcription: { used_today: 90, limit: 600 }, sync: { interval_seconds: 900 } };
const html = planView(free);
assert.ok(html.includes('<section class="settings-section"><h2>Free plan</h2>'));
assert.ok(html.includes('<div class="setting-row"><span>Storage</span><span>12.5 of 250 MB</span></div>'));
assert.ok(html.includes('<span>Voice transcription</span><span>1.5 of 10 min today</span>'));
assert.ok(html.includes('<span>Chat sync</span><span>Every 15 min</span>'));
assert.ok(!html.includes("unlimited") && !html.includes("zolang"));
const paid = planView({ ...free, plan: "paid", storage: { used: 999999999, limit: null }, transcription: { used_today: 0, limit: null }, sync: { interval_seconds: 0 } });
assert.ok(paid.includes("<h2>Paid plan</h2>"));
assert.equal(paid.match(/<em>unlimited<\/em>\*\*/g).length, 2);
assert.ok(paid.includes('<span>Chat sync</span><span>Live</span>'));
assert.ok(paid.includes("<p>** zolang de server het aankan / as long as the server can handle it</p>"));
for (const hidden of [undefined, { enabled: false }, { ...free, enabled: false }, { ...free, plan: null }]) assert.equal(planView(hidden), "");
const malicious = '<script>alert("unsafe")</script>';
assert.equal(planView({ ...free, plan: malicious }), "");
const escaped = planView({ ...free, storage: { used: malicious, limit: malicious }, transcription: { used_today: malicious, limit: malicious }, sync: { interval_seconds: malicious } });
assert.ok(!escaped.includes("<script>") && !escaped.includes("unsafe"));
assert.ok(escaped.includes("0 of 0 MB") && escaped.includes("0 of 0 min today"));
assert.ok(!planView({ ...free, storage: { used: Infinity, limit: NaN } }).includes("NaN"));
