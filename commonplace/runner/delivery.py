"""Explicit offline program packaging and code-bound delivery. No runtime authority."""

import argparse
import base64
import hashlib
import importlib.metadata
import io
import json
import os
import platform
import stat
import subprocess
import sys
import zipfile
from pathlib import Path
from types import SimpleNamespace

from .machine_setup import PROGRAM_PURPOSE, program_contents, program_pin

DEPENDENCIES = {"cryptography", "cffi", "pycparser"}


def _sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _read(path, limit):
    """Operator-supplied local files only; no links, writable peers or unbounded reads."""
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        info = os.fstat(fd)
        if (
            not stat.S_ISREG(info.st_mode)
            or info.st_uid not in (0, os.getuid())
            or info.st_mode & 0o022
            or info.st_nlink != 1
            or info.st_size > limit
        ):
            raise ValueError("unsafe program release file")
        with os.fdopen(fd, "rb", closefd=False) as stream:
            raw = stream.read(limit + 1)
        if len(raw) > limit:
            raise ValueError("program release file too large")
        return raw
    finally:
        os.close(fd)


def configure(gateway):
    """Off unless the operator explicitly provides a digest-pinned local release file."""
    path = os.environ.get("COMMONPLACE_RUNNER_PROGRAM_FILE")
    if not path:
        return
    try:
        value = json.loads(_read(path, 16384))
        if not isinstance(value, dict) or set(value) != {"pin", "archive"}:
            raise ValueError
        pin = program_pin(value["pin"])
        if not isinstance(value["archive"], str) or not Path(value["archive"]).is_absolute():
            raise ValueError
        raw = _read(value["archive"], pin["size"])
        program_contents(raw, pin)
        gateway.runner_program_release = SimpleNamespace(pin=pin, raw=raw)
    except Exception:
        raise ValueError("runner program release unavailable") from None


def pin_for(gateway):
    release = getattr(gateway, "runner_program_release", None)
    if release is None:
        return None
    pin = program_pin(release.pin)
    if len(release.raw) != pin["size"] or _sha(release.raw) != pin["sha256"]:
        raise ValueError("runner program release integrity check failed")
    return dict(pin)


def artifact(gateway, row, request):
    """The checked live pairing can obtain only the program frozen at its owner request."""
    expected = json.loads(row["program"]) if row["program"] else None
    if (
        expected is None
        or not isinstance(request, dict)
        or request != {"purpose": PROGRAM_PURPOSE, "sha256": expected["sha256"]}
        or pin_for(gateway) != expected
    ):
        raise ValueError("runner program delivery unavailable")
    return gateway.runner_program_release.raw


def build(source, output, dependencies):
    """Package tracked source and exact installed dependency versions, entirely offline.

    Dependencies are taken only from a deliberately provisioned build environment.
    Their wheel RECORD hashes must match before any bytes enter the release.
    The resulting whole-archive digest is the operator's explicit distribution pin.
    """
    if set(dependencies) != DEPENDENCIES:
        raise ValueError("all three dependency version pins are required")
    source, output = Path(source).resolve(), Path(output).absolute()
    tracked = (
        subprocess.run(
            ["git", "-C", str(source), "ls-files", "-z", "--", "commonplace", "mempalace"],
            check=True,
            capture_output=True,
        )
        .stdout.decode()
        .split("\0")
    )
    files = {}
    for relative in tracked:
        if not relative.endswith(".py"):
            continue
        path = source / relative
        if path.is_symlink() or not path.is_file():
            raise ValueError("source must contain regular tracked files")
        files["site/" + relative] = path.read_bytes()
    for name in sorted(DEPENDENCIES):
        distribution = importlib.metadata.distribution(name)
        if distribution.version != dependencies[name]:
            raise ValueError("installed dependency does not match its version pin")
        count = 0
        for record in distribution.files or ():
            relative = str(record)
            # RECORD itself and generated bytecode have no hash; neither is executable input here.
            if record.hash is None:
                continue
            if ".." in Path(relative).parts or Path(relative).is_absolute():
                raise ValueError("dependency has an external file")
            raw = Path(str(distribution.locate_file(record))).read_bytes()
            if (
                record.hash.mode != "sha256"
                or base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).decode().rstrip("=")
                != record.hash.value
            ):
                raise ValueError("dependency RECORD integrity check failed")
            key = "site/" + relative
            if key in files:
                raise ValueError("overlapping program files")
            files[key] = raw
            count += 1
        if not count:
            raise ValueError("dependency has no verified files")
    manifest = {
        "version": 1,
        "purpose": PROGRAM_PURPOSE,
        "python": sys.implementation.cache_tag,
        "system": platform.system(),
        "machine": platform.machine(),
        "dependencies": dependencies,
        "files": {name: {"sha256": _sha(raw), "size": len(raw)} for name, raw in files.items()},
    }
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, raw in sorted(files.items()):
            archive.writestr(name, raw)
        archive.writestr("program.json", json.dumps(manifest, sort_keys=True))
    raw = stream.getvalue()
    pin = {k: manifest[k] for k in ("version", "purpose", "python", "system", "machine")}
    pin.update(sha256=_sha(raw), size=len(raw))
    program_contents(raw, pin)
    config = output.with_suffix(output.suffix + ".json")
    # Never replace a previously published artifact or its distribution pin.
    for path, data in (
        (output, raw),
        (config, json.dumps({"pin": pin, "archive": str(output)}, indent=2).encode()),
    ):
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "wb") as file:
            file.write(data)
            file.flush()
            os.fsync(file.fileno())
    return pin


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Build a pinned runner program from local verified inputs"
    )
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--dependency", action="append", required=True, metavar="NAME==VERSION")
    args = parser.parse_args(argv)
    try:
        values = [value.split("==") for value in args.dependency]
        if any(len(value) != 2 for value in values) or len(dict(values)) != len(values):
            raise ValueError
        pin = build(args.source, args.output, dict(values))
    except Exception:
        print(
            "Runner program build refused; check local source and exact dependency pins.",
            file=sys.stderr,
        )
        return 1
    print(json.dumps(pin, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
