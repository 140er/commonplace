"""The inviter's two taps: keep a note in memory, approve an action as a card.

Both are explicit acts of the signed-in inviter, re-resolved from the session layer (the bot holds
no token and is not a principal), and both go through the same write paths a person's own save or
card uses, so what may be written is exactly what the inviter may write in the web app: a wing or a
project they cannot write to is refused. Nothing is filed without the tap, for anyone's request.

What is filed carries its provenance in plain words: generated by the notes bot, from which meeting
and date, on which model, citing which segments, kept or approved by whom (and edited by them, if
they edited it). A retried or doubled tap files once: the note holds a claim keyed by the request,
a memory drawer is keyed by its content and a card by the note's own id, so a crash between the
write and the record is resolved by repeating the write and recording its result.
"""

from __future__ import annotations

import json
import logging
import re

from commonplace import memory_tools, privacy, sessions
from commonplace.boards.service import BoardService
from commonplace.extensions import ToolContext, ToolError
from commonplace.meetings import engine, store

logger = logging.getLogger("commonplace.meetings")

KIND_WORDS = {
    "summary": "Summary",
    "decision": "Decision",
    "action": "Action item",
    "open_question": "Open question",
}
TITLE_MAX = 200
NOTE_MAX = 1000
BOARD = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,79}\Z")
FILING_KEYS = frozenset({"request_id", "wing"})
APPROVE_KEYS = frozenset({"request_id", "board"})


def _principal(gateway, user_id, workspace_id):
    principal = sessions.person_principal(gateway.db, user_id, workspace_id)
    if principal is None:
        raise store.Refused("not_allowed", "You can no longer file into this workspace", 403)
    return principal


def _request_id(body):
    value = body.get("request_id")
    if not isinstance(value, str) or not store.REQUEST_ID.fullmatch(value):
        raise store.Invalid("invalid_request_id", "A request id of 8-64 safe characters is needed")
    return value


def _evidence_line(note) -> str:
    parts = json.loads(note["evidence"]).get("ranges", [])
    spans = ", ".join(
        f"{p['from']}" if p["from"] == p["to"] else f"{p['from']}-{p['to']}" for p in parts
    )
    return f"segments {spans}" if spans else "no segments"


def provenance(gateway, meeting, note, inviter) -> str:
    """Where a filed note came from and who stands behind it. One text, used for memory and cards."""
    who = engine.display_label(gateway.db.user(inviter)["name"], "the inviter")
    day = (meeting["started_at"] or meeting["created_at"])[:10]
    if note["edited"]:
        return (
            f"Proposed by the notes bot from the meeting on {day}, edited and "
            f"{'approved' if note['kind'] == 'action' else 'kept'} by {who}."
        )
    verb = "approved" if note["kind"] == "action" else "kept"
    return f"Proposed by the notes bot from the meeting on {day}, {verb} by {who}."


def _memory_text(gateway, meeting, note, inviter) -> str:
    return (
        "Generated by the notes bot: model text, not the words of anyone in the meeting.\n"
        f"{provenance(gateway, meeting, note, inviter)}\n"
        f"Meeting: {meeting['title']} (id {meeting['id']}). Model: {note['model']}. "
        f"Evidence: {_evidence_line(note)}.\n\n"
        f"{KIND_WORDS[note['kind']]}: {note['text']}"
    )


def _claim(meetings, meeting_id, note_id, user_id, request_id, action):
    """The note's filing claim, after checking it is the kind this tap files."""
    if (meetings.note(meeting_id, note_id, user_id)["kind"] == "action") != action:
        raise store.Refused(
            "wrong_kind", "Approve an action as a card; keep any other note in memory", 409
        )
    return meetings.claim_filing(meeting_id, note_id, user_id, request_id)


def keep_note(gateway, workspace_id, user_id, meeting_id, note_id, body, now) -> dict:
    """*Keep*: write the note into memory as the inviter. Returns the note and whether this tap
    wrote it (a repeat returns the filed note)."""
    meetings = store.open_meetings(gateway, workspace_id)
    request_id = _request_id(body)
    meeting = meetings.meeting(meeting_id, user_id)
    wing = body.get("wing") if "wing" in body else meetings.person(user_id)["notes_wing"]
    if "wing" in body:
        wing = meetings._wing(wing)
    outcome, note = _claim(meetings, meeting_id, note_id, user_id, request_id, False)
    if outcome == "done":
        return {"note": _view(meetings, meeting_id, user_id, note), "created": False}
    try:
        if not wing:
            raise store.Refused(
                "choose_wing", "Choose a wing to file notes into (or set one in your settings)", 409
            )
        text = _memory_text(gateway, meeting, note, user_id)
        if privacy.has_secret(privacy.scan(text)):
            raise store.Refused(
                "secret_detected", "This note looks like it holds a credential; edit it first", 409
            )
        principal = _principal(gateway, user_id, workspace_id)
        ctx = ToolContext(principal=principal, gateway=gateway)
        memory_id, _, _ = memory_tools._save(
            ctx, {"text": text, "topic": "meetings", "theme": wing}
        )
    except (store.Refused, store.Invalid):
        meetings.release_filing(note_id, request_id)
        raise
    except ToolError:
        meetings.release_filing(note_id, request_id)
        raise store.Refused("cannot_file", "You cannot file into that wing", 409) from None
    view = meetings.complete_filing(note_id, request_id, memory_id, user_id, now)
    return {"note": view, "created": True}


def approve_action(gateway, workspace_id, user_id, meeting_id, note_id, body, now) -> dict:
    """*Approve*: create a card as the inviter, on a project they pick and may write to, with the
    text they saw frozen. The card's idempotency key is the note id."""
    meetings = store.open_meetings(gateway, workspace_id)
    request_id = _request_id(body)
    meeting = meetings.meeting(meeting_id, user_id)
    board = body.get("board")
    if not isinstance(board, str) or not BOARD.fullmatch(board):
        raise store.Invalid("invalid_board", "Choose the project for this card")
    outcome, note = _claim(meetings, meeting_id, note_id, user_id, request_id, True)
    if outcome == "done":
        return {"note": _view(meetings, meeting_id, user_id, note), "created": False}
    try:
        principal = _principal(gateway, user_id, workspace_id)
        text = note["text"]
        title = text if len(text) <= TITLE_MAX else text[: TITLE_MAX - 1].rstrip() + "…"
        service = BoardService(ToolContext(principal=principal, gateway=gateway))
        card = service.ensure_chat_task(
            f"meeting.{note_id}",
            {
                "board": board,
                "title": title,
                "body": f"{text}\n\n{provenance(gateway, meeting, note, user_id)}",
            },
        )
    except store.Refused:
        meetings.release_filing(note_id, request_id)
        raise
    except (ToolError, LookupError, ValueError):
        meetings.release_filing(note_id, request_id)
        raise store.Refused("cannot_file", "You cannot add cards to that project", 409) from None
    view = meetings.complete_filing(note_id, request_id, f"{board}:{card['number']}", user_id, now)
    return {"note": view, "created": True, "card": {"board": board, "number": card["number"]}}


def _view(meetings, meeting_id, user_id, note):
    return next(
        n for n in meetings.notes_for(meeting_id, user_id)["notes"] if n["id"] == note["id"]
    )
